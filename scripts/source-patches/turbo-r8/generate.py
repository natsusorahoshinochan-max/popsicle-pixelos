"""Generate the fixed TurboAdapter JAR from declared build inputs."""
import argparse
import hashlib
import json
from pathlib import Path
import runpy
import subprocess
import sys
import tempfile


def script(path, *arguments):
    previous = sys.argv
    try:
        sys.argv = [str(path), *map(str, arguments)]
        runpy.run_path(str(path), run_name='__main__')
    finally:
        sys.argv = previous


def generate(args):
    lock = json.loads(args.lock.read_text())
    if hashlib.sha256(args.apk.read_bytes()).hexdigest() != lock['apk_sha256']:
        raise ValueError('Unrecognized TurboAdapter APK')
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=args.output.parent) as temporary:
        work = Path(temporary)
        raw = work / 'raw.jar'
        names = work / 'original-types.txt'
        normalized = work / 'frames.jar'
        output = work / 'TurboAdapter-a17.jar'
        subprocess.run([str(args.converter), '-n', '-o', str(raw), str(args.apk)], check=True)
        script(args.dex_types, args.apk, names)
        subprocess.run([str(args.normalizer), str(raw), str(normalized), str(names),
                        str(args.framework), str(args.core), str(args.configinfra)], check=True)
        script(args.filter, normalized, output)
        if hashlib.sha256(output.read_bytes()).hexdigest() != lock['generated_jar_sha256']:
            raise ValueError('Generated bytecode differs from the validated fixed input')
        output.replace(args.output)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('apk', 'converter', 'normalizer', 'lock', 'dex-types', 'filter',
                 'framework', 'core', 'configinfra', 'output'):
        parser.add_argument('--' + name, type=Path, required=True)
    generate(parser.parse_args())


if __name__ == '__main__':
    main()
